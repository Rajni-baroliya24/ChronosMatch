/* Optional: node tests/browser_engine.test.cjs (no npm packages required). */
const assert = require('node:assert/strict');
const {DemoEngine} = require('../web/demo-engine.js');
const engine = new DemoEngine(null, {seed:false});
const submit=(side,price,quantity=5,symbol='AAPL')=>engine.submit({symbol,side,price,quantity,type:'LIMIT'});
const a=submit('SELL','100.01');
const b=submit('SELL','100.01');
submit('BUY','101.00',7);
assert.equal(a.status,'FILLED');
assert.equal(b.remaining,3);
assert.deepEqual(engine.trades.map(t=>[t.sell_order_id,t.price,t.quantity]),[[1,100.01,5],[2,100.01,2]]);
engine.cancel(b.id);
assert.deepEqual(engine.snapshot().asks,[]);
assert.throws(()=>engine.submit({symbol:'AAPL',side:'BUY',type:'MARKET',quantity:1}));
submit('SELL','99.99',2);
const market=engine.submit({symbol:'AAPL',side:'BUY',type:'MARKET',quantity:10});
assert.equal(market.status,'EXPIRED');
assert.equal(market.filled,2);
assert.equal(market.remaining,0);
engine.updateRisk({max_quantity:1});
assert.throws(()=>submit('BUY','100',2));
engine.tick('AAPL');
assert.equal(engine.orders.at(-1).quantity,1);
engine.updateRisk({paused:true});
assert.throws(()=>engine.tick('AAPL'));
engine.reset();
assert.equal(engine.orders.length,64);
assert.equal(engine.trades.length,0);
const result=engine.benchmark(1000);
assert.equal(result.trades,500);
assert.equal(engine.orders.length,64);
assert.ok(result.throughput>0&&result.p95>=result.median);
let saved;
const storage={setItem:(key,v)=>saved=v,getItem:key=>saved||null};
const persisted=new DemoEngine(storage);
persisted.tick('AAPL');
const restored=new DemoEngine(storage);
assert.deepEqual(restored.orders,persisted.orders);
assert.deepEqual(restored.trades,persisted.trades);
assert.equal(restored.snapshot('MSFT').trades.length,0);
console.log('Browser engine checks passed: FIFO, partial fills, cancellation, market IOC, risk, pause, reset, isolated benchmark, persistence and symbol isolation.');
